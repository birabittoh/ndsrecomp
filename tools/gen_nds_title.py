#!/usr/bin/env python3
"""Writes the cartridge banner's game titles, one per language, as a C header.

usage: gen_nds_title.py <rom.nds or unpacked folder> <out.h>

The banner (header 0x68) holds up to eight UTF-16 titles at banner+0x240, 0x100
bytes each, in firmware language order: Japanese, English, French, German,
Italian, Spanish, Chinese, Korean. A title is up to three lines: the name, an
optional subtitle and the publisher. The game's name is every line but the
last joined with ": " (a single line is taken as it is). Languages a banner
lacks (version 1 has six) are empty strings.
"""
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from nds_folder import banner_image  # noqa: E402

LANGUAGES = 8
TITLE_BYTES = 0x100
TITLES_AT = 0x240


def banner_titles(banner):
    """banner: the banner block's bytes. Returns one name per language."""
    if len(banner) < 2:
        return [""] * LANGUAGES
    version = banner[0]  # 1: six languages, 2: + Chinese, 3: + Korean
    count = {1: 6, 2: 7, 3: 8}.get(version, 6)
    titles = []
    for i in range(LANGUAGES):
        start = TITLES_AT + i * TITLE_BYTES
        if i >= count or start + TITLE_BYTES > len(banner):
            titles.append("")
            continue
        text = banner[start:start + TITLE_BYTES].decode(
            "utf-16le", errors="replace").split("\0", 1)[0]
        lines = [line.strip() for line in text.replace("\r", "").split("\n")]
        lines = [line for line in lines if line]
        if len(lines) > 1:
            lines = lines[:-1]
        name = ": ".join(lines)
        titles.append("" if "�" in name or "￿" in name else name)
    return titles


def c_string(text):
    # Three-digit octal escapes cannot swallow the character that follows.
    out = []
    for byte in text.encode("utf-8"):
        if 0x20 <= byte < 0x7F and byte not in (0x22, 0x5C, 0x3F):
            out.append(chr(byte))
        else:
            out.append("\\%03o" % byte)
    return '"' + "".join(out) + '"'


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    image = banner_image(sys.argv[1])
    titles = [""] * LANGUAGES
    if len(image) > 0x200:
        titles = banner_titles(image[0x200:])
    with open(sys.argv[2], "w", encoding="ascii", newline="\n") as out:
        out.write("// Generated by tools/gen_nds_title.py. Do not edit.\n")
        out.write("// Banner titles by firmware language: Japanese, English,\n")
        out.write("// French, German, Italian, Spanish, Chinese, Korean.\n")
        out.write("static const char* const kNdsRomTitles[8] = {\n")
        for title in titles:
            out.write("    %s,\n" % c_string(title))
        out.write("};\n")


if __name__ == "__main__":
    main()
